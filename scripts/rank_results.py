#!/usr/bin/env python3
"""Aggregate reviews in results/<tier>/*/reviews/*.yaml into results/RANKING.md."""
import statistics
import yaml
from common import ROOT, read_doc, result_dirs

CRITERIA = ["impact", "novelty", "lab_realizability", "simulation_realism", "generality", "robustness"]


def load_reviews(d):
    out = []
    for f in sorted((d / "reviews").glob("*.yaml")):
        if f.name.startswith("_"):
            continue
        r = yaml.safe_load(f.read_text()) or {}
        scores, just = r.get("scores") or {}, r.get("justification") or {}
        kept = {c: scores[c] for c in CRITERIA
                if isinstance(scores.get(c), int) and 1 <= scores[c] <= 5 and str(just.get(c, "")).strip()}
        out.append({"family": r.get("family"), "reviewer": r.get("reviewer"), "scores": kept})
    return out


def rank():
    weights = yaml.safe_load((ROOT / "results" / "weights.yaml").read_text())
    total_w = sum(weights[c] for c in CRITERIA)
    rows = []
    for d in result_dirs():
        try:
            meta, _ = read_doc(d / "RESULT.md")
        except (ValueError, FileNotFoundError):
            continue
        reviews = load_reviews(d)
        families = sorted({r["family"] for r in reviews if r["family"]})
        med, flags = {}, []
        for c in CRITERIA:
            vals = [r["scores"][c] for r in reviews if c in r["scores"]]
            if vals:
                med[c] = statistics.median(vals)
                if max(vals) - min(vals) >= 2:
                    flags.append(c)
        complete = all(c in med for c in CRITERIA)
        agg = sum(weights[c] * med[c] for c in CRITERIA) / total_w if complete else None
        rows.append({"id": meta.get("id"), "title": meta.get("title"), "status": meta.get("status"),
                     "tier": d.parent.name, "dir": f"{d.parent.name}/{d.name}", "agg": agg, "med": med, "n": len(reviews), "families": families,
                     "flags": flags, "pi": meta.get("pi_score")})
    rows.sort(key=lambda r: (r["status"] == "retracted", -(r["agg"] if r["agg"] is not None else -1)))
    return rows


def render(rows):
    lines = ["# Ranking of verified results", "",
             "Generated by `scripts/rank_results.py`. Do not edit. Rubric: `docs/RANKING_RUBRIC.md`.", ""]
    if not rows:
        lines.append("No results yet.")
        return "\n".join(lines) + "\n"
    lines += ["Tiers (docs/PROMOTION.md): **formalized** results are kernel-checked in Lean; **promising** results "
              "are cross-family verified and PI-approved but not formalized.", "",
              "| Rank | Result | Tier | Status | Score | PI | " + " | ".join(CRITERIA) + " | Reviews | Notes |",
              "|---|---|---|---|---|---|" + "---|" * len(CRITERIA) + "---|---|"]
    for k, r in enumerate(rows, 1):
        notes = []
        if len(r["families"]) < 2:
            notes.append("needs reviews from two families")
        if r["flags"]:
            notes.append("reviewers disagree on: " + ", ".join(r["flags"]))
        cells = [f"{r['med'][c]:g}" if c in r["med"] else "–" for c in CRITERIA]
        score = f"{r['agg']:.2f}" if r["agg"] is not None else "–"
        pi = r["pi"] if r["pi"] is not None else "–"
        lines.append(f"| {k} | [{r['id']}: {r['title']}]({r['dir']}/RESULT.md) | {r['tier']} | {r['status']} | {score} | {pi} | "
                     + " | ".join(cells) + f" | {r['n']} ({', '.join(r['families']) or 'none'}) | {'; '.join(notes)} |")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    (ROOT / "results" / "RANKING.md").write_text(render(rank()), encoding="utf-8")
    print("wrote results/RANKING.md")
