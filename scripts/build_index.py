#!/usr/bin/env python3
"""Regenerate problems/INDEX.md, results/RANKING.md and the dashboard block in STATUS.md."""
import collections
import datetime
import re
from common import ROOT, docs, result_dirs
import rank_results


def problems_index(problems):
    order = {"active": 0, "audited": 1, "candidate": 2, "solved": 3, "parked": 4, "demoted": 5}
    problems = sorted(problems, key=lambda x: (order.get(x[1]["status"], 9), x[1]["priority"], str(x[1]["id"])))
    lines = ["# Problem registry", "", "Generated by `scripts/build_index.py`. Do not edit.", "",
             "| Id | Title | Status | Priority | Literature | Novelty confidence | Audited by | Oracle | Claims | Results |",
             "|---|---|---|---|---|---|---|---|---|---|"]
    for p, m, _ in problems:
        lines.append(f"| [{m['id']}]({p.name}) | {m['title']} | {m['status']} | {m['priority']} | "
                     f"{m['literature_state']} | {m['novelty_confidence']} | {', '.join(m.get('audited_by') or []) or '–'} | "
                     f"{m['oracle_ready']} | {len(m.get('claims') or [])} | {len(m.get('results') or [])} |")
    lines += ["", "## Target quantities", ""]
    for p, m, _ in problems:
        lines.append(f"- **{m['id']}** — {m['target_quantity']}")
    return "\n".join(lines) + "\n"


def dashboard(problems, claims, tasks, ranking):
    def table(counter, order):
        keys = [k for k in order if k in counter] + sorted(k for k in counter if k not in order)
        return " · ".join(f"{k}: {counter[k]}" for k in keys) or "none"

    pc = collections.Counter(m["status"] for _, m, _ in problems)
    cc = collections.Counter(m["status"] for _, m, _ in claims)
    tc = collections.Counter(m["status"] for _, m, _ in tasks)
    logs = sorted(p.name for p in (ROOT / "log").glob("*.md") if not p.name.startswith("_") and p.name != "README.md")
    lines = [f"Updated {datetime.date.today().isoformat()}.", "",
             f"- **Problems** ({len(problems)}): " + table(pc, ["active", "audited", "candidate", "solved", "parked", "demoted"]),
             f"- **Claims** ({len(claims)}): " + table(cc, ["proposed", "cheap-checks-passed", "sim-verified", "audited", "promoted", "refuted", "withdrawn"]),
             f"- **Tasks** ({len(tasks)}): " + table(tc, ["open", "blocked", "done", "cancelled"]),
             f"- **Results** ({len(ranking)}): " + table(collections.Counter(r["tier"] for r in ranking), ["formalized", "promising"])
             + (f" (top: {ranking[0]['id']})" if ranking else ""),
             f"- **Log entries**: {len(logs)}" + (f" (latest: `{logs[-1]}`)" if logs else ""), ""]
    by_priority = lambda m: (m["priority"], str(m["id"]))
    for_pi = sorted((m for _, m, _ in tasks if m["status"] == "open" and str(m["family_required"]) == "human"), key=by_priority)
    if for_pi:
        lines += ["Waiting on the PI:", ""] + [f"- `{m['id']}` (p{m['priority']}) — {m['title']}" for m in for_pi] + [""]
    blocked = sorted((m for _, m, _ in tasks if m["status"] == "blocked"), key=by_priority)
    if blocked:
        lines += ["Blocked (the task file says on what):", ""] + [f"- `{m['id']}` (p{m['priority']}) — {m['title']}" for m in blocked] + [""]
    adv = [m for _, m, _ in claims if m["status"] in {"cheap-checks-passed", "sim-verified", "audited"}]
    if adv:
        lines += ["Claims in the pipeline:", ""] + [f"- `{m['id']}` ({m['status']}) — {m['title']}" for m in adv] + [""]
    open_tasks = sorted((m for _, m, _ in tasks if m["status"] == "open" and str(m["family_required"]) != "human"), key=by_priority)
    if open_tasks:
        lines += ["Open tasks by priority:", ""] + [
            f"- `{m['id']}` (p{m['priority']}, {m['type']}, {m['family_required']}) — {m['title']}" for m in open_tasks[:15]]
    return "\n".join(lines)


def main():
    problems, claims, tasks = list(docs("problems")), list(docs("claims")), list(docs("tasks"))
    (ROOT / "problems" / "INDEX.md").write_text(problems_index(problems), encoding="utf-8")
    ranking = rank_results.rank()
    (ROOT / "results" / "RANKING.md").write_text(rank_results.render(ranking), encoding="utf-8")
    status = ROOT / "STATUS.md"
    text = status.read_text(encoding="utf-8")
    block = "<!-- DASHBOARD:START -->\n" + dashboard(problems, claims, tasks, ranking) + "\n<!-- DASHBOARD:END -->"
    text = re.sub(r"<!-- DASHBOARD:START -->.*?<!-- DASHBOARD:END -->", lambda _: block, text, flags=re.S)
    status.write_text(text, encoding="utf-8")
    print("wrote problems/INDEX.md, results/RANKING.md, STATUS.md dashboard")


if __name__ == "__main__":
    main()
