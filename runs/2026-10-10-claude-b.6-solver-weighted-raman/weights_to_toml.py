"""Convert weights_for_solver.json (claude-b's weights, copied unchanged) to weights.toml for
the Julia driver (the solver environment has no JSON package as a direct dependency).

Usage (repository root):
  ~/agent-work/venv/bin/python runs/2026-10-10-claude-b.6-solver-weighted-raman/weights_to_toml.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
src = json.load(open(os.path.join(HERE, "weights_for_solver.json")))
names = ("w_centroid", "w_lambda_gen_eigvec", "w_best_binary")
lines = ["# generated by weights_to_toml.py from weights_for_solver.json; bins_k in claude-b's numpy convention"]
for key, d in src["points"].items():
    lines.append(f'["{key}"]')
    bins = [int(b) for b in d["bins_k"]]
    assert len(set(bins)) == len(bins)
    lines.append(f"bins_k = [{', '.join(str(b) for b in bins)}]")
    for n in names:
        vals = [float(x) for x in d[n]]
        assert len(vals) == len(bins)
        lines.append(f"{n} = [{', '.join(repr(v) for v in vals)}]")
    lines.append("")
with open(os.path.join(HERE, "weights.toml"), "w") as f:
    f.write("\n".join(lines))
print("wrote weights.toml with points", list(src["points"]))
