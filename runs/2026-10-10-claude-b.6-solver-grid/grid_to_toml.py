"""Convert weights_grid_for_solver.json (claude-b, copied unchanged) to grid.toml for the Julia driver.

Usage (repository root):
  ~/agent-work/venv/bin/python runs/2026-10-10-claude-b.6-solver-grid/grid_to_toml.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
src = json.load(open(os.path.join(HERE, "weights_grid_for_solver.json")))
names = ("w_centroid", "w_lambda_gen_eigvec", "w_best_binary")
lines = ["# generated by grid_to_toml.py from weights_grid_for_solver.json; bins_k in claude-b's numpy convention"]
for key, d in src["points"].items():
    lines.append(f'["{key}"]')
    lines.append(f"N = {float(d['N'])!r}")
    lines.append(f"zr = {float(d['zr'])!r}")
    lines.append(f"xi = {float(d['xi'])!r}")
    lines.append(f"Nt = {int(d['Nt'])}")
    lines.append(f"TW = {float(d['TW'])!r}")
    bins = [int(b) for b in d["bins_k"]]
    assert len(set(bins)) == len(bins)
    lines.append(f"bins_k = [{', '.join(str(b) for b in bins)}]")
    for n in names:
        vals = [float(x) for x in d[n]]
        assert len(vals) == len(bins)
        lines.append(f"{n} = [{', '.join(repr(v) for v in vals)}]")
    lines.append("")
with open(os.path.join(HERE, "grid.toml"), "w") as f:
    f.write("\n".join(lines))
print("wrote grid.toml with", len(src["points"]), "points")
