"""Convert filters_for_solver.json (claude-b's filter definitions) to filters.toml,
which the Julia driver reads with the TOML standard library (the solver
environment has no JSON package as a direct dependency).

Usage (repository root):
  ~/agent-work/venv/bin/python runs/2026-10-10-claude-b.6-solver-nd-check/filters_to_toml.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
src = json.load(open(os.path.join(HERE, "filters_for_solver.json")))
lines = ["# generated by filters_to_toml.py from filters_for_solver.json; bins k mean Omega T0 = k 2pi/40"]
for key, d in src.items():
    lines.append(f'["{key}"]')
    lines.append(f"bin_spacing_omegaT0 = {d['bin_spacing_omegaT0']!r}")
    for name in ("best_binary_bins", "best_interval_bins"):
        bins = [int(b) for b in d[name]]
        assert len(set(bins)) == len(bins)
        lines.append(f"{name} = [{', '.join(str(b) for b in bins)}]")
    lines.append("")
with open(os.path.join(HERE, "filters.toml"), "w") as f:
    f.write("\n".join(lines))
print("wrote filters.toml with keys", list(src))
